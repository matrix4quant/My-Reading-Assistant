const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bridge', {
  chooseFiles: () => ipcRenderer.invoke('choose-files'),
  listBooks: () => ipcRenderer.invoke('list-books'),
  saveBook: (book) => ipcRenderer.invoke('save-book', book),
  loadBook: (id) => ipcRenderer.invoke('load-book', id),
  updateProgress: (id, progress) => ipcRenderer.invoke('update-progress', id, progress),
  saveAnnotations: (id, annotations) => ipcRenderer.invoke('save-annotations', id, annotations),
  deleteBook: (id) => ipcRenderer.invoke('delete-book', id),
  openLib: () => ipcRenderer.invoke('open-lib'),
  libPath: () => ipcRenderer.invoke('lib-path'),
  appVersion: () => ipcRenderer.invoke('app-version'),
  menuInfo: () => ipcRenderer.invoke('menu-info'),
  menuTest: (action) => ipcRenderer.invoke('menu-test', action),
  windowTest: (action) => ipcRenderer.invoke('window-test', action),
  uiTexts: () => ipcRenderer.invoke('ui-texts'),
  settingsGet: () => ipcRenderer.invoke('settings-get'),
  settingsSetCloseAction: (value) => ipcRenderer.invoke('settings-set-close-action', value),
  onMenuAction: (cb) => ipcRenderer.on('menu-action', (event, action) => cb(action)),
  copyText: (text) => ipcRenderer.invoke('clipboard-write', text),
  readSource: (filePath) => ipcRenderer.invoke('read-source', filePath),
  extractEpubImages: (bookId, epubPath, refs) => ipcRenderer.invoke('extract-epub-images', bookId, epubPath, refs),
  extractPdfImages: (bookId, pdfPath) => ipcRenderer.invoke('extract-pdf-images', bookId, pdfPath),
  saveImageFiles: (bookId, files) => ipcRenderer.invoke('save-image-files', bookId, files),
  imageUrl: (bookId, rel) => ipcRenderer.invoke('image-url', bookId, rel),
  ttsVoices: () => ipcRenderer.invoke('tts-voices'),
  ttsSynth: (args) => ipcRenderer.invoke('tts-synth', args),
  ttsPrefetch: (args) => ipcRenderer.invoke('tts-prefetch', args),
  weblibLoad: () => ipcRenderer.invoke('weblib-load'),
  weblibSave: (cfg) => ipcRenderer.invoke('weblib-save', cfg),
  weblibResolveDomain: () => ipcRenderer.invoke('weblib-resolve-domain'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url)
});
